const PATH_TOUCHES = ["authority", "policy", "migration", "visual", "security", "perf"] as const;

function hasLineCounts(file: ChangedFile): boolean {
  return Number.isFinite(file.additions) && Number.isFinite(file.deletions);
}

/** A rename counts as generated only when it also came from a generated path, so moving a source file there still counts. */
function isGenerated(file: ChangedFile, generated: readonly string[]): boolean {
  return matchesAny(file.path, generated) && (file.previousPath === undefined || matchesAny(file.previousPath, generated));
}

const lineSum = (files: readonly ChangedFile[]) => files.reduce((sum, f) => sum + f.additions + f.deletions, 0);

/**
 * Additions plus deletions with generated files left out; undefined when any file carries no counts. Generated lines
 * that alone pass `largeLines` are no regeneration but a hand edit, so then every line counts.
 */
export function changedLineCount(files: readonly ChangedFile[], rules: Pick<ClassRules, "generated" | "largeLines"> = DEFAULT_CLASS_RULES): number | undefined {
  if (!files.every(hasLineCounts)) return undefined;
  const generated = lineSum(files.filter((f) => isGenerated(f, rules.generated)));
  const all = lineSum(files);
  return generated > rules.largeLines ? all : all - generated;
}

/** The review-rounds audit (2026-10-11): security slices past about this many lines rarely converge in 3 rounds. */
export const SECURITY_SLICE_LINES = DEFAULT_CLASS_RULES.largeLines;

/** An oversize security or guard-area slice: its non-generated size, the cap it passed, and the guard paths it touches. */
export interface SliceFlag {
  lines: number;
  cap: number;
  guardPaths: string[];
}

export interface SliceInput {
  kind?: string;
  changedFiles: readonly ChangedFile[];
}

/**
 * Flags a slice over the cap when it is kind `security` or touches a security or authority path outside the generated
 * set. Advisory only, so an unreadable count flags nothing.
 */
export function securitySliceFlag(input: SliceInput, rules: ClassRules = DEFAULT_CLASS_RULES): SliceFlag | undefined {
  const lines = changedLineCount(input.changedFiles, rules);
  if (lines === undefined || lines <= SECURITY_SLICE_LINES) return undefined;
  const guards = [...rules.security, ...rules.authority];
  const guardPaths = input.changedFiles.filter((f) => !isGenerated(f, rules.generated) && matchesAny(f.path, guards)).map((f) => f.path);
  if (input.kind !== "security" && guardPaths.length === 0) return undefined;
  return { lines, cap: SECURITY_SLICE_LINES, guardPaths };
}

function isLarge(files: readonly ChangedFile[], rules: ClassRules): boolean {
  const lines = changedLineCount(files, rules);
  return lines === undefined ? files.length > rules.largeFiles : lines > rules.largeLines;
}

function isUntested(paths: readonly string[], rules: ClassRules): boolean {
  const tests = paths.some((p) => matchesAny(p, rules.test));
  return !tests && paths.some((p) => matchesAny(p, rules.source));
}

function collectTouches(facts: PrFacts, rules: ClassRules): Set<PrTouch> {
  const paths = facts.changedFiles.map((f) => f.path);
  const touches = new Set<PrTouch>();
  for (const touch of PATH_TOUCHES) if (paths.some((p) => matchesAny(p, rules[touch]))) touches.add(touch);
  if (facts.authorityTouch) touches.add("authority");
  if (facts.policyTouch) touches.add("policy");
  if (facts.kind === "security") touches.add("security");
  if (isUntested(paths, rules)) touches.add("untested");
  if (isLarge(facts.changedFiles, rules)) touches.add("large");
  return touches;
}

const STRICT: readonly PrTouch[] = ["authority", "policy", "security", "migration", "large"];
const ORDER: readonly PrTouch[] = ["authority", "policy", "migration", "visual", "security", "perf", "untested", "large"];

/** Class and touch flags from signals alone; no model reads the diff. An unread kind takes the strict class. */
export function classifyPr(facts: PrFacts, rules: ClassRules = DEFAULT_CLASS_RULES): PrClass {
  const found = collectTouches(facts, rules);
  const unread = facts.kind === undefined || facts.kind === "unknown";
  const strict = unread || STRICT.some((t) => found.has(t));
  return { class: strict ? "g10" : "standard", touches: ORDER.filter((t) => found.has(t)) };
}
