import type { Profile } from "../schema/profile.js";
import type { StyleRule } from "../schema/style-rule.js";
import type { GeneratedFile } from "./types.js";

function getConvention(
  section: Record<string, StyleRule>,
  key: string,
  infoThreshold: number,
): StyleRule["convention"] | undefined {
  const rule = section[key];
  if (!rule || rule.confidence < infoThreshold) return undefined;
  return rule.convention;
}

function indentAndNewlineLines(
  formatting: Record<string, StyleRule>,
  infoThreshold: number,
): string[] {
  const lines: string[] = [];

  const indentStyle = getConvention(
    formatting,
    "indentStyle",
    infoThreshold,
  );
  if (indentStyle) {
    const value =
      indentStyle === "spaces"
        ? "space"
        : indentStyle === "tabs"
          ? "tab"
          : indentStyle;
    lines.push(`indent_style = ${value}`);
  }

  const indentSize = getConvention(
    formatting,
    "indentSize",
    infoThreshold,
  );
  if (indentSize !== undefined) {
    lines.push(`indent_size = ${indentSize}`);
  }

  const trailingNewline = getConvention(
    formatting,
    "trailingNewline",
    infoThreshold,
  );
  if (trailingNewline !== undefined) {
    lines.push(`insert_final_newline = ${trailingNewline}`);
  }

  return lines;
}

export function generateEditorConfigExport(
  profile: Profile,
): GeneratedFile {
  const formatting = profile.formatting;
  const infoThreshold = profile.severityThresholds.info;
  const lines: string[] = [];

  lines.push("# Generated by codewatch");
  lines.push("root = true");
  lines.push("");
  lines.push("[*]");
  lines.push(...indentAndNewlineLines(formatting, infoThreshold));

  lines.push("end_of_line = lf");
  lines.push("charset = utf-8");
  lines.push("trim_trailing_whitespace = true");

  const lineLength = getConvention(
    formatting,
    "lineLength",
    infoThreshold,
  );
  if (lineLength !== undefined) {
    lines.push(`max_line_length = ${lineLength}`);
  }

  lines.push("");

  return {
    path: ".editorconfig",
    content: lines.join("\n"),
  };
}
