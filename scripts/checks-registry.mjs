// Rule-to-class registry (TP-6483): every titan/* lint rule, structure check and .codewatch/check.json rule names the
// review-finding class keys it catches, so a review step can leave out a class a rule already covers.
// `node scripts/checks-registry.mjs` rewrites checks-registry.json; structure.test.mjs fails when it is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// The fixed class-key vocabulary of the review audit, grouped by each key's default route.
const CLASS_KEYS_BY_ROUTE = {
  design: [
    "fail-open-on-missing-or-unreadable-input",
    "approval-or-gate-bypass",
    "parallel-reader-diverges",
    "fix-applied-to-one-branch",
    "unlocked-read-modify-write",
    "stale-read-after-wait",
    "visibility-leak",
  ],
  test: ["parser-edge-case", "producer-consumer-mismatch", "missing-branch-test", "test-name-overclaims", "test-checks-nothing"],
  structure: [
    "stale-doc-after-contract-change",
    "doc-omits-new-flag-or-kind",
    "cli-flag-not-wired",
    "unused-public-api",
    "release-ordering",
    "changeset-rules",
    "task-done-when-unmet",
  ],
  type: ["hand-written-schema-drift", "consumer-enum-missing-member", "wrong-signature"],
  analysis: ["duplicated-helper", "attestation-contradicts-diff", "multi-step-sequence-bug"],
  lint: ["unsafe-file-read", "path-containment", "swallowed-error", "real-clock-in-test", "import-order", "formatting", "duplicate-test-block", "complexity"],
  prompt: ["prose-claim-false", "external-api-semantics", "toctou-race"],
  none: [
    "logic-bug-one-off",
    "stale-code-comment",
    "stale-pr-description",
    "naming",
    "ordering-or-sort",
    "known-gap-stated",
    "preexisting-behaviour",
    "cosmetic",
    "status-noise",
  ],
};
const CLASS_KEYS = new Set(Object.values(CLASS_KEYS_BY_ROUTE).flat());
// A rule may name a class the vocabulary lacks the way the review parser records one: `other:<kebab-slug>`.
const OTHER_KEY = /^other:[a-z0-9]+(?:-[a-z0-9]+)*$/;
const REGISTRY_FILE = "checks-registry.json";

const isClassKey = (key) => CLASS_KEYS.has(key) || OTHER_KEY.test(key);
const listOf = (value) => (Array.isArray(value) ? [...value] : []);

/** One [rule id, classes] entry per rule, sorted by id; a rule that names no classes gets an empty list. */
export function collectRuleClasses({ eslintRules, structureModule, checkRules }) {
  const entries = [
    ...Object.entries(eslintRules).map(([name, rule]) => [`titan/${name}`, listOf(rule.meta?.docs?.classes)]),
    ...Object.entries(structureModule)
      .filter(([name, value]) => name.startsWith("check") && typeof value === "function")
      .map(([name, check]) => [`structure/${name}`, listOf(check.classes)]),
    ...checkRules.map((rule) => [`codewatch/${rule.id}`, listOf(rule.$classes)]),
  ];
  return entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/** One remediation message per rule that names no class or names a key outside the vocabulary. */
export function classProblems(entries) {
  return entries.flatMap(([id, classes]) => {
    if (classes.length === 0) return [`\`${id}\` names no class key. Add the review-finding classes it catches (scripts/checks-registry.mjs lists them).`];
    return classes
      .filter((key) => !isClassKey(key))
      .map((key) => `\`${id}\` names \`${key}\`, which is not a class key. Use a key from scripts/checks-registry.mjs, or \`other:<kebab-slug>\`.`);
  });
}

export function renderRegistry(entries) {
  const registry = {
    $comment: "Generated by scripts/checks-registry.mjs; do not edit. Rule id -> the review-finding class keys it covers (TP-6483).",
    rules: Object.fromEntries(entries),
  };
  return `${JSON.stringify(registry, null, 2)}\n`;
}

/** Reads the three rule sources of the repo at root; the lint rules come from the built eslint-plugin. */
export async function loadRuleClasses(root) {
  const plugin = await import(pathToFileURL(join(root, "packages/eslint-plugin/dist/index.js")).href);
  const structureModule = await import(pathToFileURL(join(root, "scripts/structure-rules.mjs")).href);
  const checkRules = JSON.parse(readFileSync(join(root, ".codewatch/check.json"), "utf8")).rules;
  return collectRuleClasses({ eslintRules: plugin.default.rules, structureModule, checkRules });
}

async function main() {
  const root = dirname(dirname(fileURLToPath(import.meta.url)));
  const entries = await loadRuleClasses(root);
  const problems = classProblems(entries);
  if (problems.length > 0) {
    problems.forEach((problem) => console.error(problem));
    process.exit(1);
  }
  writeFileSync(join(root, REGISTRY_FILE), renderRegistry(entries));
  console.log(`Wrote ${REGISTRY_FILE} with ${entries.length} rules.`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) await main();
